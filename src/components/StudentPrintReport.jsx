import React from "react";

const fmt = (d) =>
  d ? new Date(d).toLocaleDateString(undefined, { dateStyle: "medium" }) : "—";

export default function StudentPrintReport({ student, gradeables, sectionLabel }) {
  const quizzes = gradeables.filter((g) => g.kind === "quiz");
  const taken = quizzes.filter((q) => q.percent !== null && q.percent !== undefined);
  const quizAvg = taken.length
    ? Math.round(taken.reduce((s, q) => s + q.percent, 0) / taken.length)
    : null;
  const graded = gradeables.filter(
    (g) => g.percent !== null && g.percent !== undefined
  );
  const overall = graded.length
    ? Math.round(graded.reduce((s, g) => s + g.percent, 0) / graded.length)
    : null;

  return (
    <div className="px-10 py-12 text-black bg-white">
      <header className="flex items-start justify-between border-b-2 border-black pb-3 mb-5">
        <div>
          <h1 className="text-2xl font-bold leading-tight">
            {student.full_name || "Student"}
          </h1>
          <p className="text-sm text-gray-700 mt-1">
            Period {student.class_period || "—"}
            {student.grade ? ` · Grade ${student.grade}` : ""}
          </p>
        </div>
        <div className="text-right text-sm">
          <p className="font-semibold">Student Progress Report</p>
          {sectionLabel && <p className="text-gray-600">{sectionLabel}</p>}
          <p className="text-gray-600">
            {new Date().toLocaleDateString(undefined, { dateStyle: "long" })}
          </p>
        </div>
      </header>

      {overall !== null && (
        <p className="mb-2 text-sm">
          <span className="font-semibold">Current overall grade:</span> {overall}%
        </p>
      )}
      {quizAvg !== null && (
        <p className="mb-3 text-sm">
          <span className="font-semibold">Quiz average:</span> {quizAvg}%
        </p>
      )}

      <table className="w-full text-sm border-collapse">
        <thead>
          <tr className="bg-gray-100 text-left">
            <th className="border border-gray-300 px-2 py-1 w-8 text-center">#</th>
            <th className="border border-gray-300 px-2 py-1">Item</th>
            <th className="border border-gray-300 px-2 py-1">Type</th>
            <th className="border border-gray-300 px-2 py-1 text-center">Score / Grade</th>
            <th className="border border-gray-300 px-2 py-1 text-center">%</th>
            <th className="border border-gray-300 px-2 py-1">Date</th>
            <th className="border border-gray-300 px-2 py-1">Status</th>
          </tr>
        </thead>
        <tbody>
          {gradeables.map((g, i) => (
            <tr key={i}>
              <td className="border border-gray-300 px-2 py-1 text-center">{i + 1}</td>
              <td className="border border-gray-300 px-2 py-1">{g.name}</td>
              <td className="border border-gray-300 px-2 py-1 capitalize">{g.kind}</td>
              <td className="border border-gray-300 px-2 py-1 text-center">{g.value}</td>
              <td className="border border-gray-300 px-2 py-1 text-center">
                {g.percent !== null && g.percent !== undefined ? `${g.percent}%` : "—"}
              </td>
              <td className="border border-gray-300 px-2 py-1">{fmt(g.date)}</td>
              <td className="border border-gray-300 px-2 py-1">{g.status}</td>
            </tr>
          ))}
        </tbody>
      </table>

      <footer className="mt-8 text-xs text-gray-500">
        Generated by the Base44 classroom app.
      </footer>
    </div>
  );
}